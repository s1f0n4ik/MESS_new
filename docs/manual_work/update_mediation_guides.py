def paragraphs(doc):
    for p in doc.paragraphs:
        yield p
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                yield from cell.paragraphs


def before(doc, anchor, text, style='Normal'):
    p = doc.add_paragraph(text, style=style)
    anchor.addprevious(p._p)
    return p


def heading(doc, anchor, text, level=2):
    return before(doc, anchor, text, f'Heading {level}')


def steps(doc, anchor, items):
    for n, text in enumerate(items, 1):
        before(doc, anchor, f'{n}. {text}')


def image(doc, anchor):
    if not SHOT.is_file():
        return
    p = before(doc, anchor, '')
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(str(SHOT), width=Inches(6.5))
    p = before(doc, anchor, 'Пример отдельной медиации во встроенном редакторе десктопного приложения')
    for r in p.runs:
        r.font.size = Pt(9)


def remove_section(doc, start, end):
    first = next(p for p in doc.paragraphs if p.text == start and p.style.name.startswith('Heading'))
    last = next(p for p in doc.paragraphs if p.text.startswith(end) and p.style.name.startswith('Heading'))
    node = first._p
    while node is not last._p:
        following = node.getnext()
        node.getparent().remove(node)
        node = following
    return last._p


