def run():
    BACKUP.mkdir(parents=True, exist_ok=True)
    names = [
        ('Postcards Studio Инструкция веб сервиса.docx', web_update),
        ('Postcards Руководство пользователя.docx', desktop_update),
        ('Postcards Краткая инструкция для выставки.docx', brief_update),
    ]
    for name, update in names:
        path = OUT / name
        for source in (path, path.with_suffix('.pdf')):
            if source.exists() and not (BACKUP / source.name).exists():
                copy2(source, BACKUP / source.name)
        doc = Document(path)
        update(doc); normalize(doc); doc.save(path)
        print(path)


if __name__ == '__main__':
    run()
