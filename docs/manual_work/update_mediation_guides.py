def normalize(doc):
    for p in paragraphs(doc):
        text = p.text
        text = re.sub(r'Версия от \d{1,2} (?:октября|ноября) 2026', 'Версия от 8 ноября 2026', text)
        text = text.replace('2.0.2', '2.0.4').replace('2.0.3', '2.0.4')
        text = re.sub(r'Редакция руководства \d{1,2} (?:октября|ноября) 2026 года', 'Редакция руководства 8 ноября 2026 года', text)
        if text != p.text:
            p.text = text
    doc.core_properties.modified = datetime(2026, 11, 8, 12, tzinfo=timezone.utc)
    for name in ('Title','Heading 1','Heading 2','Heading 3'):
        if name in doc.styles:
            doc.styles[name].font.color.rgb = RGBColor(0,0,0)
    for table in doc.tables:
        for row in table.rows:
            props = row._tr.get_or_add_trPr()
            if props.find(qn('w:cantSplit')) is None:
                props.append(OxmlElement('w:cantSplit'))


